export const SHIPMENTS_TEXT: SectionTexts<typeof ru> = { ru, en, fa };

/** A day such as 31.07.2026 written in the interface language (Persian digits for fa). */
export function shipmentDay(value: string | Date, locale: string) {
  return new Intl.DateTimeFormat(locale, { day: '2-digit', month: '2-digit', year: 'numeric' }).format(new Date(value));
}

/** Date and time; `timeZone` for moments the partners quote in Almaty time. */
export function shipmentDateTime(value: string | Date, locale: string, timeZone?: string) {
  return new Intl.DateTimeFormat(locale, { dateStyle: 'short', timeStyle: 'short', timeZone }).format(new Date(value));
}

/** A short "day month" such as 31 Jul. */
export function shipmentDayMonth(value: string | Date, locale: string) {
  return new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short' }).format(new Date(value));
}
