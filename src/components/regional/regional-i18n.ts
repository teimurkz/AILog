export const REGIONAL_TEXT: SectionTexts<RegionalTexts> = { ru, en, fa };

export function regionalTexts(language: string): RegionalTexts {
  return pickTexts(REGIONAL_TEXT, language);
}

export function regionalLocale(language: string): string {
  return CRM_LOCALES[language as CrmLanguage] ?? CRM_LOCALES.en;
}

/** Formats a stored 'YYYY-MM-DD' day for the interface language; other values are shown as entered. */
export function formatRegionalDay(value: string | undefined, locale: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})/.exec(value || '');
  if (!match) return value || '';
  return new Intl.DateTimeFormat(locale, { day: '2-digit', month: '2-digit', year: 'numeric', timeZone: 'UTC' })
    .format(new Date(Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3]))));
}

/** Report route "Алматы → Астана" with the missing-place marker in the interface language. */
export function localizeReportRoute(route: string, texts: RegionalTexts): string {
  return route.split(' → ').map(place => place === REGIONAL_REPORT_UNKNOWN_PLACE ? texts.common.notSpecified : place).join(' → ');
}

/** Report validation errors come from shared code in Russian. */
export function localizeReportError(message: string, texts: RegionalTexts): string {
  if (message === REGIONAL_REPORT_ERRORS.reversedPeriod) return texts.report.periodReversed;
  if (message === REGIONAL_REPORT_ERRORS.invalidPeriod) return texts.report.periodInvalid;
  return texts.report.checkPeriod;
}

const SERVER_PATTERNS: Array<[RegExp, (texts: RegionalTexts['server'], match: RegExpExecArray) => string]> = [
  [/^🟢 В движении \((\d+) км\/ч\)$/u, (s, m) => s.moving(Number(m[1]))],
  [/^🟡 Нет новых координат \((\d+) мин\)$/u, (s, m) => s.noNewCoordinates(Number(m[1]))],
  [/^🔴 Нет сигнала \((\d+) мин\. назад\)$/u, (s, m) => s.noSignal(Number(m[1]))],
  [/^~(\d+) ч (\d+) мин \(при 70 км\/ч\)$/, (s, m) => `${s.etaHours(Number(m[1]), Number(m[2]))} ${s.at70}`],
  [/^~(\d+) ч (\d+) мин$/, (s, m) => s.etaHours(Number(m[1]), Number(m[2]))],
  [/^~(\d+) мин$/, (s, m) => s.etaMinutes(Number(m[1]))],
];

/** The GPS server sends status and ETA texts in Russian; show them in the interface language. */
export function localizeGpsText(value: string | undefined, language: string): string | undefined {
  if (!value || language === 'ru') return value;
  const texts = regionalTexts(language).server;
  for (const [key, russian] of Object.entries(ru.server)) {
    if (russian === value) return texts[key as keyof typeof texts] as string;
  }
  for (const [pattern, build] of SERVER_PATTERNS) {
    const match = pattern.exec(value);
    if (match) return build(texts, match);
  }
  return value;
}
